# Computes the identity of the game sources (src/engine and src/fheroes2), checked by network games: two games built
# from the same sources have the same one, on PC as on Android. The script writes a C++ header defining it
# (MULTI_SOURCE_ID) and rewrites it only when it changes.
#
# android/app/build.gradle does the same: the .cpp and .h files are sorted by path (with /), "path \n content without
# \r \n" of each file is hashed with SHA-256 and the first 16 hexadecimal digits are kept.
#
# Called by the Visual Studio build:
#   powershell -ExecutionPolicy Bypass -File script\windows\generate_source_id.ps1 <header to write>

param(
    [Parameter(Mandatory = $true)] [string] $Header
)

$ErrorActionPreference = 'Stop'

$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$files = foreach ($dir in @('src\engine', 'src\fheroes2')) {
    Get-ChildItem (Join-Path $root $dir) -Recurse -File | Where-Object { $_.Extension -ceq '.cpp' -or $_.Extension -ceq '.h' } | ForEach-Object {
        [pscustomobject]@{ Path = $_.FullName.Substring($root.Length + 1).Replace('\', '/'); FullPath = $_.FullName }
    }
}

$sorted = [System.Collections.Generic.List[object]]::new($files)
$sorted.Sort([System.Comparison[object]] { param($a, $b) [string]::CompareOrdinal($a.Path, $b.Path) })

$sha = [System.Security.Cryptography.SHA256]::Create()
$newLine = [byte[]] @(10)
$latin1 = [System.Text.Encoding]::GetEncoding(28591)

foreach ($file in $sorted) {
    $path = [System.Text.Encoding]::UTF8.GetBytes($file.Path)
    $content = [System.IO.File]::ReadAllBytes($file.FullPath)
    # Latin-1 keeps every byte as it is while the \r are removed.
    $withoutReturns = $latin1.GetBytes($latin1.GetString($content).Replace("`r", ''))

    [void] $sha.TransformBlock($path, 0, $path.Length, $null, 0)
    [void] $sha.TransformBlock($newLine, 0, 1, $null, 0)
    if ($withoutReturns.Length -gt 0) {
        [void] $sha.TransformBlock($withoutReturns, 0, $withoutReturns.Length, $null, 0)
    }
    [void] $sha.TransformBlock($newLine, 0, 1, $null, 0)
}
[void] $sha.TransformFinalBlock([byte[]] @(), 0, 0)

$id = (($sha.Hash | Select-Object -First 8 | ForEach-Object { $_.ToString('x2') }) -join '')
$text = "// Generated by script/windows/generate_source_id.ps1: identity of the game sources.`n#pragma once`n#define MULTI_SOURCE_ID 0x$($id)ULL`n"

$previous = if (Test-Path -LiteralPath $Header) { [System.IO.File]::ReadAllText($Header) } else { '' }
if ($previous -ne $text) {
    New-Item -ItemType Directory -Force (Split-Path $Header) | Out-Null
    [System.IO.File]::WriteAllText($Header, $text)
}

Write-Output "Source identity: $id"
